const temperature = 10;

switch (temperature) {
    case 10:
        console.log('Temperatura baixa.')
        break;
    case 20:
        console.log('Temperatura amena.')
        break;
    case 30:
        console.log('Temperatura alta.')
        break;
    
    default:
        console.log('Temperatura desconhecida.')
        break;
}